/**
 * Trajectory friction, split by what the evidence is actually about.
 *
 * Task knowledge (which files were inspected, what was already seen) is
 * intent-scoped: it survives until the user's entry changes, because a handoff
 * does not un-read a file. Struggle evidence (recurrence, persistent failures,
 * displacement, stagnation) is owner-scoped: it only ever describes the
 * capability that produced it, so it resets when the serving model changes.
 * Without that split, model A's failures can be republished as proof that
 * model B is struggling, and the router cascades A → B → C on A's evidence.
 *
 * Provider invocations must not reset either scope.
 */
import type { Dimension } from '../../types.js';
import type {
  PendingTrajectoryEscalation,
  ProgressKind,
  StruggleDecision,
} from './types.js';
import {
  classifyTrajectoryStruggle,
  MB_MIN_MUTATIONS,
  type CycleRecord,
  type TrajectorySnapshot,
} from './detectors.js';
import {
  cycleFromToolResult,
  isVerifier,
  lineDistance,
  MAX_DIFF_MS,
  applyReplacement,
  type ObservedCycle,
  type ToolCycleInput,
} from './fingerprints.js';

const MAX_CYCLES = 8;
const MAX_EVIDENCE = 256;
const MAX_FAILURES = 32;
const MAX_VERIFIERS = 16;
const MAX_BATCH = 32;
const MAX_SEEN = 128;
/** File bodies are kept only to measure mutation displacement. */
const MAX_SNAPSHOT_FILES = 16;
const MAX_SNAPSHOT_FILE_BYTES = 1_000_000;
const MAX_SNAPSHOT_TOTAL_BYTES = 8_000_000;

interface FileSnapshot {
  baseline: string;
  current: string;
  /** Only mutated files contribute to gross and net displacement. */
  mutated: boolean;
  /** Cached baseline→current distance; null once proven unavailable. */
  net: number | null | undefined;
}

interface VerifierFailureState {
  activeFailures: Set<string>;
  corrections: Map<string, number>;
  lastVerifier: Map<string, number>;
}

function emptyVerifierState(): VerifierFailureState {
  return {
    activeFailures: new Set(),
    corrections: new Map(),
    lastVerifier: new Map(),
  };
}

export class TrajectoryState {
  private intentKey: string | undefined;
  private ownerKey: string | undefined;
  private cycles: CycleRecord[] = [];
  private evidenceFrontier = new Set<string>();
  private verifierFailures = new Map<string, VerifierFailureState>();
  private lastMutationInvocation = -1;
  private mutationCount = 0;
  private grossDistance = 0;
  private files = new Map<string, FileSnapshot>();
  private mbTrusted = true;
  private stagnationRun = 0;
  private pending: PendingTrajectoryEscalation | undefined;
  private lastEscalateFingerprint: string | undefined;
  private pendingCalls: Array<{ toolCallId: string; toolName: string; input?: unknown }> = [];
  private pendingResults = new Map<string, ToolCycleInput>();
  private completedIds = new Set<string>();

  reset(): void {
    this.intentKey = undefined;
    this.ownerKey = undefined;
    this.evidenceFrontier.clear();
    this.files.clear();
    this.pendingCalls = [];
    this.pendingResults.clear();
    this.completedIds.clear();
    this.resetStruggle();
  }

  bindIntent(intentKey: string): void {
    if (this.intentKey === intentKey) return;
    this.reset();
    this.intentKey = intentKey;
  }

  /**
   * Bind struggle evidence to the capability that is producing it. Called
   * before each observation, so counters only ever hold cycles generated by
   * the model named in a pending escalation. File snapshots survive, rebased
   * to current, so the next owner's displacement is measured from where it
   * actually started.
   */
  bindOwner(ownerKey: string | undefined): void {
    if (!ownerKey || this.ownerKey === ownerKey) return;
    const hadOwner = this.ownerKey !== undefined;
    this.ownerKey = ownerKey;
    if (hadOwner) this.resetStruggle();
  }

  snapshot(deadline = Date.now() + MAX_DIFF_MS): TrajectorySnapshot {
    return {
      cycles: this.cycles,
      mutationCount: this.mutationCount,
      grossDistance: this.grossDistance,
      ...this.netDisplacement(deadline),
      stagnationRun: this.stagnationRun,
      failureCorrections: this.correctionsBySignature(),
    };
  }

  observeToolResult(event: ToolCycleInput, invocation: number): StruggleDecision | undefined {
    if (this.completedIds.has(event.toolCallId)) {
      return undefined;
    }
    const inBatch = this.pendingCalls.some((call) => call.toolCallId === event.toolCallId);
    if (inBatch) {
      if (!this.pendingResults.has(event.toolCallId)) {
        this.pendingResults.set(event.toolCallId, event);
      }
      if (!this.pendingCalls.every((call) => this.pendingResults.has(call.toolCallId))) {
        return undefined;
      }
      return this.flushBatch(invocation);
    }
    const deadline = Date.now() + MAX_DIFF_MS;
    this.rememberCompleted(event.toolCallId);
    const observed = cycleFromToolResult(event, invocation);
    this.applyCycle(observed, deadline);
    return classifyTrajectoryStruggle(this.snapshot(deadline));
  }

  noteToolCall(toolName: string, toolCallId: string, input?: unknown): StruggleDecision | undefined {
    if (this.completedIds.has(toolCallId)) return undefined;
    if (this.pendingCalls.some((call) => call.toolCallId === toolCallId)) return undefined;
    let flushed: StruggleDecision | undefined;
    if (this.pendingResults.size > 0) {
      // Results already arrived for the previous batch. A new call means that
      // batch is closed; missing siblings were blocked preflights (ours or
      // another extension's). The caller must arm from the returned
      // decision — cycles are applied here, but pending escalation is not.
      flushed = this.abandonUnresolvedCalls();
    }
    this.pendingCalls.push({ toolCallId, toolName, input });
    if (this.pendingCalls.length > MAX_BATCH) this.pendingCalls.shift();
    return flushed;
  }

  abandonUnresolvedCalls(): StruggleDecision | undefined {
    if (this.pendingCalls.length === 0) return undefined;
    if (this.pendingResults.size > 0) {
      return this.flushBatch(this.lastMutationInvocation < 0 ? 0 : this.lastMutationInvocation);
    }
    this.pendingCalls = [];
    this.pendingResults.clear();
    return undefined;
  }

  peekPending(): PendingTrajectoryEscalation | undefined {
    return this.pending;
  }

  setPending(pending: PendingTrajectoryEscalation | undefined): void {
    this.pending = pending;
  }

  consumePending(): PendingTrajectoryEscalation | undefined {
    const pending = this.pending;
    this.pending = undefined;
    return pending;
  }

  maybeArmPending(
    decision: StruggleDecision,
    fromModel: string | undefined,
    dimension: Dimension | undefined,
    preOutput: boolean,
  ): void {
    if (!fromModel || !dimension) return;
    // Evidence belongs to the owner that produced it. A claim against any
    // other model would be an accusation nothing in this state supports.
    if (this.ownerKey !== undefined && fromModel !== this.ownerKey) return;
    if (!decision.escalate) {
      this.pending = undefined;
      this.lastEscalateFingerprint = undefined;
      return;
    }
    const fingerprint = decision.signals
      .map((signal) => `${signal.kind}:${signal.severity}:${signal.evidenceIds.join(',')}`)
      .join('|');
    if (fingerprint === this.lastEscalateFingerprint) return;
    this.lastEscalateFingerprint = fingerprint;
    this.pending = {
      fromModel,
      dimension,
      signals: decision.signals.filter((signal) => signal.severity === 'warning' || signal.severity === 'severe'),
      tfi: decision.tfi,
      preOutput,
    };
  }

  private resetStruggle(): void {
    this.cycles = [];
    this.verifierFailures.clear();
    this.lastMutationInvocation = -1;
    this.mutationCount = 0;
    this.grossDistance = 0;
    this.stagnationRun = 0;
    this.mbTrusted = true;
    this.pending = undefined;
    this.lastEscalateFingerprint = undefined;
    for (const entry of this.files.values()) {
      entry.baseline = entry.current;
      entry.mutated = false;
      entry.net = undefined;
    }
  }

  /**
   * Net displacement is only an input to backtracking, which cannot fire below
   * `MB_MIN_MUTATIONS`, so it is computed lazily and cached per file version.
   * An unavailable comparison makes the whole signal untrusted rather than
   * contributing a zero that would read as "everything was reverted".
   */
  private netDisplacement(deadline: number): { netDistance: number; mbTrusted: boolean } {
    if (!this.mbTrusted) return { netDistance: 0, mbTrusted: false };
    if (this.mutationCount < MB_MIN_MUTATIONS || this.grossDistance <= 0) {
      return { netDistance: 0, mbTrusted: true };
    }
    let netDistance = 0;
    for (const entry of this.files.values()) {
      if (!entry.mutated) continue;
      if (entry.net === undefined) {
        if (Date.now() >= deadline) {
          this.mbTrusted = false;
          return { netDistance: 0, mbTrusted: false };
        }
        const distance = lineDistance(entry.baseline, entry.current, deadline);
        entry.net = distance.available ? distance.added + distance.deleted : null;
      }
      if (entry.net === null) return { netDistance: 0, mbTrusted: false };
      netDistance += entry.net;
    }
    return { netDistance, mbTrusted: true };
  }

  private correctionsBySignature(): ReadonlyMap<string, number> {
    const merged = new Map<string, number>();
    for (const state of this.verifierFailures.values()) {
      for (const [signature, count] of state.corrections) {
        merged.set(signature, Math.max(merged.get(signature) ?? 0, count));
      }
    }
    return merged;
  }

  private rememberCompleted(toolCallId: string): void {
    this.completedIds.add(toolCallId);
    if (this.completedIds.size > MAX_SEEN) {
      const first = this.completedIds.values().next().value;
      if (first) this.completedIds.delete(first);
    }
  }

  private flushBatch(invocation: number): StruggleDecision {
    const deadline = Date.now() + MAX_DIFF_MS;
    for (const call of this.pendingCalls) {
      const event = this.pendingResults.get(call.toolCallId);
      if (!event) continue;
      this.rememberCompleted(call.toolCallId);
      this.applyCycle(cycleFromToolResult({
        ...event,
        toolName: call.toolName,
        toolCallId: call.toolCallId,
        input: event.input ?? call.input,
      }, invocation), deadline);
    }
    this.pendingCalls = [];
    this.pendingResults.clear();
    return classifyTrajectoryStruggle(this.snapshot(deadline));
  }

  private applyCycle(observed: ObservedCycle, deadline: number): void {
    this.trackFileSnapshot(observed);
    const progressKind = this.classifyProgress(observed);
    if (observed.action.family === 'mutation' && observed.progressHint.isError !== true) {
      this.mutationCount += 1;
      this.lastMutationInvocation = observed.invocation;
      this.applyMutationDisplacement(observed, deadline);
    }

    if (isVerifier(observed.action)) {
      this.updateFailures(observed);
    }

    if (progressKind === 'progress') {
      this.stagnationRun = 0;
      this.evidenceFrontier.add(observed.evidenceId);
    } else if (progressKind === 'none') {
      this.stagnationRun += 1;
    } else if (
      observed.action.family === 'read'
      || observed.action.family === 'search'
      || observed.action.commandClass === 'inspect'
    ) {
      this.evidenceFrontier.add(observed.evidenceId);
    }

    this.cycles.push({
      invocation: observed.invocation,
      action: observed.action,
      observationKey: observed.observationKey,
      observationVerified: observed.observationVerified,
      progressKind,
      failureSignature: observed.progressHint.failureSignature,
      evidenceId: observed.evidenceId,
    });
    if (this.cycles.length > MAX_CYCLES) this.cycles.shift();
    if (this.evidenceFrontier.size > MAX_EVIDENCE) {
      const first = this.evidenceFrontier.values().next().value;
      if (first) this.evidenceFrontier.delete(first);
    }
  }

  private trackFileSnapshot(observed: ObservedCycle): void {
    const path = observed.action.path ?? observed.progressHint.mutationPath;
    const body = observed.progressHint.fileBody;
    if (!path || !body) return;
    if (observed.action.family !== 'read' || this.files.has(path)) return;
    if (body.length > MAX_SNAPSHOT_FILE_BYTES) return;
    this.files.set(path, { baseline: body, current: body, mutated: false, net: undefined });
    this.evictSnapshots();
  }

  /**
   * Snapshots exist for mutation backtracking, so unmutated files are evicted
   * first. Dropping a mutated file would leave its gross displacement counted
   * with no matching net displacement, overstating backtracking — that case
   * makes the signal untrusted instead.
   */
  private evictSnapshots(): void {
    let bytes = 0;
    for (const entry of this.files.values()) bytes += entry.baseline.length + entry.current.length;
    while (this.files.size > MAX_SNAPSHOT_FILES || bytes > MAX_SNAPSHOT_TOTAL_BYTES) {
      let victim: string | undefined;
      for (const [path, entry] of this.files) {
        if (!entry.mutated) {
          victim = path;
          break;
        }
      }
      if (victim === undefined) {
        victim = this.files.keys().next().value;
        if (victim === undefined) return;
        this.mbTrusted = false;
      }
      const entry = this.files.get(victim)!;
      bytes -= entry.baseline.length + entry.current.length;
      this.files.delete(victim);
    }
  }

  private applyMutationDisplacement(observed: ObservedCycle, deadline: number): void {
    if (!this.mbTrusted || Date.now() >= deadline) {
      this.mbTrusted = false;
      return;
    }
    const path = observed.progressHint.mutationPath ?? observed.action.path;
    if (!path) {
      this.mbTrusted = false;
      return;
    }
    const next = this.nextFileBody(path, observed);
    if (next == null) {
      this.mbTrusted = false;
      return;
    }
    const entry = this.files.get(path);
    if (!entry) {
      if (next.length > MAX_SNAPSHOT_FILE_BYTES) {
        this.mbTrusted = false;
        return;
      }
      this.files.set(path, { baseline: next, current: next, mutated: true, net: undefined });
      this.evictSnapshots();
      return;
    }
    const step = lineDistance(entry.current, next, deadline);
    if (!step.available) {
      this.mbTrusted = false;
      return;
    }
    this.grossDistance += step.added + step.deleted;
    entry.current = next;
    entry.mutated = true;
    entry.net = undefined;
    this.evictSnapshots();
  }

  private nextFileBody(path: string, observed: ObservedCycle): string | undefined {
    if (observed.progressHint.fileBody != null) return observed.progressHint.fileBody;
    const oldText = observed.progressHint.mutationOldText;
    const newText = observed.progressHint.mutationNewText;
    if (oldText == null || newText == null) return undefined;
    const current = this.files.get(path)?.current;
    if (current == null) return undefined;
    return applyReplacement(current, oldText, newText);
  }

  private classifyProgress(observed: ObservedCycle): ProgressKind {
    if (observed.action.family === 'mutation') return 'unknown';
    if (!observed.observationVerified || observed.action.equivalenceVerified === false) return 'unknown';
    if (
      observed.action.family === 'read'
      || observed.action.family === 'search'
      || observed.action.commandClass === 'inspect'
    ) {
      return this.evidenceFrontier.has(observed.evidenceId) ? 'none' : 'progress';
    }
    if (isVerifier(observed.action)) {
      const state = this.verifierFailures.get(observed.action.key);
      const active = state?.activeFailures ?? new Set<string>();
      const signature = observed.progressHint.failureSignature;
      if (!observed.progressHint.isError && !signature) {
        // Only this verifier's own failures are resolved by its own pass.
        return active.size > 0 ? 'progress' : 'unknown';
      }
      if (signature && active.size > 0 && !active.has(signature)) {
        // A different failure is a different failure, not an improvement.
        // Without evidence the failure set or severity actually shrank, the
        // honest answer is that nothing is known about progress.
        return 'unknown';
      }
      if (signature || observed.progressHint.isError) return 'none';
      return 'unknown';
    }
    return 'unknown';
  }

  /**
   * Failure state is per verifier: a passing `tsc` says nothing about a
   * failing `pytest`, and clearing one with the other is how a genuinely
   * persistent failure escapes detection across a mixed verifier loop.
   */
  private updateFailures(observed: ObservedCycle): void {
    const key = observed.action.key;
    const signature = observed.progressHint.failureSignature;
    if (!observed.progressHint.isError && !signature) {
      this.verifierFailures.delete(key);
      return;
    }
    if (!signature) return;

    let state = this.verifierFailures.get(key);
    if (!state) {
      state = emptyVerifierState();
      this.verifierFailures.set(key, state);
    }

    for (const existing of [...state.activeFailures]) {
      if (existing !== signature) {
        state.activeFailures.delete(existing);
        state.corrections.delete(existing);
        state.lastVerifier.delete(existing);
      }
    }

    const lastVerifier = state.lastVerifier.get(signature) ?? -1;
    if (
      state.activeFailures.has(signature)
      && this.lastMutationInvocation > lastVerifier
      && this.lastMutationInvocation < observed.invocation
    ) {
      state.corrections.set(signature, (state.corrections.get(signature) ?? 0) + 1);
    }
    state.activeFailures.add(signature);
    state.lastVerifier.set(signature, observed.invocation);
    if (state.corrections.size > MAX_FAILURES) {
      const first = state.corrections.keys().next().value;
      if (first) state.corrections.delete(first);
    }
    if (this.verifierFailures.size > MAX_VERIFIERS) {
      const first = this.verifierFailures.keys().next().value;
      if (first !== undefined && first !== key) this.verifierFailures.delete(first);
    }
  }
}
